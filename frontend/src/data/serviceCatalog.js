const bySlug = new Map(SERVICES.map((svc) => [svc.slug, svc]));
const aliasToSlug = new Map();
SERVICES.forEach((svc) => (svc.aliases || []).forEach((a) => aliasToSlug.set(a, svc.slug)));

export const getService = (slug) => bySlug.get(slug) || bySlug.get(aliasToSlug.get(slug));
export const canonicalSlug = (slug) => (bySlug.has(slug) ? slug : aliasToSlug.get(slug) || null);
export const getCategory = (key) => CATEGORIES.find((c) => c.key === key);
export const servicePath = (svc) => svc.path || `/services/${svc.slug}`;
export const servicesInCategory = (key) =>
  SERVICES.filter((svc) => svc.category === key || (svc.alsoIn || []).includes(key));

export const withGst = (fee) => Math.round(fee * (1 + GST_RATE));
export const inr = (n) => `₹${Math.round(n).toLocaleString('en-IN')}`;
export const formatFee = (svc) =>
  svc.fee === 0 ? 'Free' : `${svc.from ? 'from ' : ''}${inr(svc.fee)}`;
