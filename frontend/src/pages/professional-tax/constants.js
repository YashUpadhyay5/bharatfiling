export const getPtPlan = (planId = 'elite') => {
  const norm = String(planId).toLowerCase();
  const plan = PT_PLANS.find(
    (p) => p.id === norm || p.alias === norm || (norm === 'starter' && p.id === 'starter') || (norm === 'elite' && p.id === 'elite')
  );
  return plan || PT_PLANS[1] || PT_PLANS[0];
};

